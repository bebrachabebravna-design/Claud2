/** Подставляет реквизиты в плейсхолдеры {op_xxx} и {op_rows}. */
function fill_ops(string $html): string {
    $html = str_replace('{op_rows}', op_req_rows(), $html);
    return preg_replace_callback('/\{op_([a-z]+)\}/', fn($m) => op($m[1]), $html);
}

