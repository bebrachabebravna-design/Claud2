/** Собирает оглавление и проставляет id заголовкам h2. */
function with_toc(string $html): array {
    $n = 0;
    $items = [];
    $out = preg_replace_callback('#<h2>(.*?)</h2>#s', function ($m) use (&$n, &$items) {
        $n++;
        $id = 'p' . $n;
        $items[] = '<li><a href="#' . $id . '">' . strip_tags($m[1]) . '</a></li>';
        return '<h2 id="' . $id . '">' . $m[1] . '</h2>';
    }, $html);
    $toc = '<nav class="lg-toc"><b>Содержание документа</b><ol>' . implode('', $items) . '</ol></nav>';
    return [$toc, $out];
}

