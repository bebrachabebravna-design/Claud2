            doc_terms()],
    ];
    $written = [];
    foreach ($docs as [$slug, $title, $metaTitle, $desc, $intro, $bodyRaw]) {
        [$toc, $body] = with_toc(fill_ops($bodyRaw));
        $html = legal_page($slug, $title, $metaTitle, $desc, $intro, $toc, $body);
