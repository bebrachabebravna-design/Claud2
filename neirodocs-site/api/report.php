<?php
// Персональные рекомендации для отчёта калькулятора потерь.
// Принимает цифры калькулятора и сферу компании, спрашивает нейросеть через
// Polza.ai (OpenAI-совместимый API) и возвращает простые, понятные новичку
// советы: где теряются деньги, как команде начать пользоваться обычными
// нейросетями и готовые запросы под его сферу. Ключ хранится на сервере.
declare(strict_types=1);
require __DIR__ . '/config.php';

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store');

function fail(string $why): void {
    echo json_encode(['ok' => false, 'why' => $why], JSON_UNESCAPED_UNICODE);
    exit;
}

if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') fail('method');

$raw = file_get_contents('php://input');
if ($raw === false || strlen($raw) > 4096) fail('input');
$in = json_decode($raw, true);
if (!is_array($in)) fail('json');

// --- Валидация входа ---
$num = static function ($v, int $min, int $max): int {
    $v = (int)$v;
    return max($min, min($max, $v));
};
$N = $num($in['employees'] ?? 0, 1, 10000);
$S = $num($in['requests'] ?? 0, 1, 200);
$M = $num($in['minutes'] ?? 0, 1, 240);
$H = $num($in['rate'] ?? 0, 50, 50000);
$sphere = trim(mb_substr((string)($in['sphere'] ?? ''), 0, 200));
if ($sphere === '') $sphere = 'не указана (обычная компания малого/среднего бизнеса)';

$hoursMo = $N * $S * $M / 60 * 21;
$lossMo = (int)round($hoursMo * $H);
$recover = (int)round($lossMo * 0.9);

// --- Лимит на IP (защита бюджета) ---
$ip = $_SERVER['REMOTE_ADDR'] ?? 'unknown';
$dir = __DIR__ . '/data';
if (!is_dir($dir)) @mkdir($dir, 0775, true);
$limFile = $dir . '/rate_' . date('Ymd') . '_' . preg_replace('/[^a-f0-9.:]/i', '', $ip) . '.cnt';
$count = is_file($limFile) ? (int)file_get_contents($limFile) : 0;
if ($count >= REPORT_IP_LIMIT) fail('limit');
@file_put_contents($limFile, (string)($count + 1));
if (random_int(1, 100) === 1) {
    foreach (glob($dir . '/rate_*.cnt') ?: [] as $f) {
        if (strpos($f, date('Ymd')) === false) @unlink($f);
    }
}

// --- Запрос к нейросети ---
$fmt = static fn(int $v): string => number_format($v, 0, ',', ' ') . ' ₽';
$system = <<<TXT
Ты — эксперт по оптимизации бизнес-процессов с помощью ИИ в компании «Нейродокс».
Посетитель сайта ввёл цифры своей компании и сферу. Готовишь ему БЕСПЛАТНЫЙ ПЕРСОНАЛЬНЫЙ РАЗБОР:
как оптимизировать рутину в документах. Это подарок, а не продажа — дай максимум пользы.

ПРО ЧИТАТЕЛЯ: собственник или руководитель, НЕ разбирается в нейросетях, слова «промпт», «LLM»
ему непонятны — пиши «запрос для нейросети», «ИИ». Пиши просто, по-деловому, коротко.

ГЛАВНОЕ ТРЕБОВАНИЕ — КОНКРЕТИКА ПОД ЕГО НИШУ. Каждый пункт обязан упоминать реальные документы,
процессы и роли именно его отрасли. Пример нужной глубины (это про стройку — АДАПТИРУЙ под сферу клиента,
не копируй): сметы, акты КС-2/КС-3, исполнительная документация, договоры с подрядчиками, прорабы,
сметчики, ПТО; боль — «прораб на объекте не может быстро уточнить пункт договора с подрядчиком».
Такой же уровень конкретики выдай для сферы клиента. Общие фразы («сотрудники долго ищут информацию»,
«проведите обучение команды») — ЗАПРЕЩЕНЫ.

ПРО ЦИФРЫ — СТРОГО: используй ТОЛЬКО цифры, которые тебе передали (потери, сотрудники, минуты).
ЗАПРЕЩЕНО выдумывать любые другие суммы, проценты и статистику. Если хочется усилить пункт цифрой,
а её нет — пиши без цифры.

ТОН: не утверждай категорично, что у клиента точно так — пиши «обычно в вашей сфере», «чаще всего»,
«как правило». Если сфера непонятна, бессмысленна или не указана — не притворяйся, что знаешь её:
дай крепкий общий разбор для малого/среднего бизнеса и нигде не упоминай выдуманную отрасль.

Отвечай СТРОГО валидным JSON без markdown, по-русски:
{"quick_win":{"title":"...","text":"...","result":"..."},
 "pains":[{"title":"...","text":"..."}],
 "plan":[{"day":"...","title":"...","text":"..."}],
 "templates":[{"title":"...","where":"...","prompt":"..."}],
 "security":["..."],
 "agent_next":"..."}

quick_win — ЧТО ДАСТ РЕЗУЛЬТАТ ПРЯМО СЕЙЧАС ЗА 10 МИНУТ: одно конкретное действие с документом его сферы
(заполнить типовой документ по шаблону или проверить договор через нейросеть), которое можно сделать
сразу после прочтения. Пиши глаголами «Откройте», «вставьте», «получите».
title — 3-6 слов. text — 2-3 предложения с точными шагами (какую нейросеть открыть, что вставить, какой запрос).
result — ОБЯЗАТЕЛЬНО: что это действие даёт в итоге, ощутимой выгодой (например: «Готовая таблица рисков по
договору за 2 минуты вместо часа работы юриста» или «Заполненный акт вместо 20 минут ручного переноса данных»).

pains — ровно 3: где ОБЫЧНО в его нише утекают деньги и время из-за документов. Называй конкретные
документы и роли отрасли. Без выдуманных сумм.

templates — САМАЯ ВАЖНАЯ ЧАСТЬ. Ровно 3 ПРОРАБОТАННЫХ, ПОДРОБНЫХ запроса под ЕГО нишу, каждый работает
с реальным документом отрасли. Автоматизация работы с документами — главная польза, раскрой её:
1) ЗАПОЛНЕНИЕ / АВТОСОСТАВЛЕНИЕ типового документа его сферы по шаблону — обязательно советуй Claude
   (пометь «через VPN», лучший для этого), безопасная альтернатива — GigaChat;
2) ПРОВЕРКА важного документа его сферы на риски и ключевые условия (таблицей);
3) быстрый ответ клиенту или сотруднику по правилам компании — российские нейросети (GigaChat, Алиса —
   «без VPN, безопасно для рабочих данных»).
where — куда вставлять и почему. prompt — ПОЛНЫЙ, ПОДРОБНЫЙ готовый текст с [вставьте ваш документ]
и пояснением внутри, что подставить; не куцый, а такой, чтобы сразу дал качественный результат.

plan — ровно 4 шага («День 1»...«День 4») с учётом размера команды: кому поручить (роль его отрасли),
с какого документа начать, что сделать за день. Конкретно, выполнимо.

security — ровно 3 коротких правила «как дать команде ИИ и не слить данные» с примерами документов
его сферы (что можно в зарубежные нейросети, что только в российские).

agent_next — 1-2 предложения, МЯГКО и без продажи: ручной способ означает вставлять каждый документ
самому; если захочется, чтобы ИИ знал все документы компании сразу и отвечал сам, — это следующий шаг,
можно просто спросить нас в Telegram. Без слов «купите», «закажите», без цен.

Нейросети для советов: GigaChat (giga.chat), Алиса (alice.yandex.ru) — российские, без VPN, безопасны
для рабочих данных; Claude (claude.ai) — через VPN, лучший для документов; ChatGPT (chatgpt.com) — через VPN.
Не упоминай конкурентов и цены. Не выдумывай факты о компании клиента.
TXT;

$user = "Сфера компании: {$sphere}. Сотрудников, которые ищут информацию: {$N}. " .
    "Обращений за информацией в день на человека: {$S}. Минут на один поиск: {$M}. " .
    "Ставка: {$H} ₽/час. Потери: {$fmt($lossMo)}/мес. Возврат с ИИ-агентом: до {$fmt($recover)}/мес.";

$models = array_merge([POLZA_MODEL],
    defined('POLZA_MODELS_FALLBACK') ? array_filter(array_map('trim', explode(',', POLZA_MODELS_FALLBACK))) : []);

$out = null;
foreach ($models as $model) {
    $payload = json_encode([
        'model' => $model,
        'messages' => [
            ['role' => 'system', 'content' => $system],
            ['role' => 'user', 'content' => $user],
        ],
        'temperature' => 0.4,
        'max_tokens' => 2000,
    ], JSON_UNESCAPED_UNICODE);

    $ch = curl_init(POLZA_BASE . '/chat/completions');
    curl_setopt_array($ch, [
        CURLOPT_POST => true,
        CURLOPT_POSTFIELDS => $payload,
        CURLOPT_HTTPHEADER => [
            'Content-Type: application/json',
            'Authorization: Bearer ' . POLZA_API_KEY,
        ],
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT => 30,
        CURLOPT_CONNECTTIMEOUT => 10,
    ]);
    $resp = curl_exec($ch);
    $code = curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
    curl_close($ch);
    if ($resp === false || $code >= 400) continue;

    $data = json_decode($resp, true);
    $text = $data['choices'][0]['message']['content'] ?? '';
    if (!is_string($text) || $text === '') continue;
    // модель могла добавить пояснения вокруг JSON — вырезаем от первой { до последней }
    $s = strpos($text, '{');
    $e = strrpos($text, '}');
    if ($s === false || $e === false || $e <= $s) continue;
    $cand = json_decode(substr($text, $s, $e - $s + 1), true);
    if (is_array($cand) && !empty($cand['pains']) && !empty($cand['plan']) && !empty($cand['templates'])) {
        $out = $cand;
        break;
    }
}
if ($out === null) fail('upstream');

echo json_encode(['ok' => true, 'data' => $out], JSON_UNESCAPED_UNICODE);
