/* ---------- ПОДПИСИ ВОЗРАСТА НА КАРТОЧКАХ ---------- */
function yearLabel(n) {
  const mod10 = n % 10, mod100 = n % 100;
  if (n === 0) return 'самое начало';
  if (mod10 === 1 && mod100 !== 11) return n + ' год';
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return n + ' года';
  return n + ' лет';
}
